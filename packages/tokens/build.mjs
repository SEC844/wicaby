// Writes the Graphite colour tokens (tokens.json) out for each app:
//   apps/desktop/src/renderer/tokens.css                          CSS custom properties, one block per theme
//   apps/android/core/src/main/java/com/wika/wicaby/core/ui/Tokens.kt   ARGB constants for tv, mobile, livetv-ui, mesh-ui
// Usage: node packages/tokens/build.mjs   (tools/checks/tokens-check.mjs fails when the outputs are stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '../..');
export const OUTPUTS = {
  css: 'apps/desktop/src/renderer/tokens.css',
  kotlin: 'apps/android/core/src/main/java/com/wika/wicaby/core/ui/Tokens.kt',
};
const HEADER = 'Generated by packages/tokens/build.mjs from packages/tokens/tokens.json: edit that file and run the script.';
// Theme keys that are not colour roles.
const META = new Set(['scheme', 'tv', 'system', 'accent-fg']);
// Roles only the Android apps draw (an opaque lifted surface): not emitted to CSS.
const ANDROID_ONLY = new Set(['raised', 'raised-focus']);

const own = (o) => Object.entries(o).filter(([k]) => !k.startsWith('$'));
export const load = () => JSON.parse(fs.readFileSync(path.join(import.meta.dirname, 'tokens.json'), 'utf8'));

/** '#abc', '#aabbcc' or 'rgb(r g b / a)' to [r, g, b, a] with a in 0..1. */
export function rgba(css) {
  let m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(css);
  if (m) {
    const h = m[1].length === 3 ? [...m[1]].map((c) => c + c).join('') : m[1];
    return [...[0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)), 1];
  }
  if ((m = /^rgb\((\d+) (\d+) (\d+)(?: \/ ([\d.]+))?\)$/.exec(css))) return [...m.slice(1, 4).map(Number), m[4] === undefined ? 1 : Number(m[4])];
  throw new Error(`tokens: unsupported colour ${css}`);
}

/** CSS colour to Kotlin ARGB ('0xFFAABBCCL'); alpha rounds like the hand-written values did. */
export function argb(css) {
  const [r, g, b, a] = rgba(css);
  return '0x' + [Math.round(a * 255), r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase() + 'L';
}

/**
 * Every theme fully resolved: { id, scheme, tv, roles: {name: css}, system: {name: css}, accents: [{id, name, color, fg}] }.
 * The first theme is the base the others extend.
 */
export function resolve(tokens = load()) {
  const entries = own(tokens.themes);
  const base = entries[0][1];
  const roles = (t) => Object.fromEntries(own(t).filter(([k]) => !META.has(k)));
  return entries.map(([id, t]) => {
    const system = { ...tokens.system, ...(t.system ?? {}) };
    const fgs = t['accent-fg'] ?? {};
    return {
      id,
      scheme: t.scheme ?? base.scheme,
      tv: t.tv ?? true,
      roles: { ...roles(base), ...roles(t) },
      system,
      accents: tokens.accents.map((a) => ({ id: a.id, name: a.color, color: system[a.color] ?? a.color, fg: fgs[a.id] ?? a.fg })),
    };
  });
}

// 'bg-elevated-2' -> 'elevated2' (the Compose name), 'label-2' -> 'label2', 'raised-focus' -> 'raisedFocus'.
const kt = (name) => name.replace(/^bg-(?=.)/, '').replace(/-(\w)/g, (_, c) => (/\d/.test(c) ? c : c.toUpperCase()));
const cap = (s) => s[0].toUpperCase() + s.slice(1);

export function render(tokens = load()) {
  const themes = resolve(tokens);
  const [base] = themes;
  const accentCss = (a) => (tokens.system[a.name] ? `var(--${a.name})` : a.color);

  // CSS: every theme is a full block, so a preview card with its own data-theme (ThemeCards) renders any theme
  // inside any other. --accent is declared in each block so var(--blue) resolves to that theme's tone.
  const css = [`/* ${HEADER} */`];
  for (const t of themes) {
    css.push(t === base ? `:root,\n[data-theme='${t.id}'] {` : `[data-theme='${t.id}'] {`);
    for (const [k, v] of Object.entries(t.roles)) if (!ANDROID_ONLY.has(k)) css.push(`  --${k}: ${v};`);
    css.push('');
    for (const [k, v] of Object.entries(t.system)) css.push(`  --${k}: ${v};`);
    css.push('', `  --accent: ${accentCss(t.accents[0])};`, `  --accent-fg: ${t.accents[0].fg};`, `  color-scheme: ${t.scheme};`, '}', '');
  }
  // Media surfaces (hero, item page, player, photo viewer) stay dark in a light theme, like tv.apple.com:
  // their text sits on artwork and dark scrims. The accent keeps the theme's tone.
  for (const t of themes.filter((x) => x.scheme === 'light')) {
    css.push(`[data-theme='${t.id}'] .on-media {`);
    for (const [k, v] of Object.entries(base.roles)) if (!ANDROID_ONLY.has(k)) css.push(`  --${k}: ${v};`);
    css.push('  color-scheme: dark;', '  color: var(--label);', '}', '');
  }
  for (const a of base.accents) css.push(`[data-accent='${a.id}'] { --accent: ${accentCss(a)}; --accent-fg: ${a.fg}; }`);
  css.push('');
  for (const t of themes.slice(1)) {
    t.accents.forEach((a, i) => {
      if (a.fg !== base.accents[i].fg) css.push(`[data-theme='${t.id}'][data-accent='${a.id}'] { --accent-fg: ${a.fg}; }`);
    });
  }

  // Kotlin: ARGB Longs, because :core has no Compose UI; the UI modules wrap them in Color().
  const names = Object.keys(base.roles);
  const sys = Object.keys(tokens.system);
  const k = [
    `// ${HEADER}`,
    'package com.wika.wicaby.core.ui',
    '',
    '/** Graphite colour tokens as ARGB (docs/design.md). :core has no Compose UI, so the apps wrap them in Color(). */',
    'object Tokens {',
    '    class Accent(val id: String, val argb: Long, val onArgb: Long)',
    '',
    '    class System(',
    ...sys.map((n) => `        val ${n}: Long,`),
    '    )',
    '',
    '    /** One theme: role colours (same names as the desktop CSS custom properties), system colours and the accents in its tones. */',
    '    class Palette(',
    '        val id: String,',
    '        val light: Boolean,',
    '        /** False for a theme the TV never offers (light). */',
    '        val tv: Boolean,',
    ...names.map((n) => `        val ${kt(n)}: Long,`),
    '        val system: System,',
    '        /** In the order Prefs stores (an index); the first is the default. */',
    '        val accents: List<Accent>,',
    '    )',
  ];
  for (const t of themes) {
    k.push('', `    val ${cap(t.id)} = Palette(`, `        id = "${t.id}",`, `        light = ${t.scheme === 'light'},`, `        tv = ${t.tv},`);
    k.push(...names.map((n) => `        ${kt(n)} = ${argb(t.roles[n])},`));
    k.push(`        system = System(${sys.map((n) => argb(t.system[n])).join(', ')}),`, '        accents = listOf(');
    for (const a of t.accents) k.push(`            Accent("${a.id}", ${argb(a.color)}, ${argb(a.fg)}),`);
    k.push('        ),', '    )');
  }
  k.push(
    '',
    '    /** Every theme in the order the settings list them; the first is the default. */',
    `    val Themes = listOf(${themes.map((t) => cap(t.id)).join(', ')})`,
    '',
    '    /** The palette for a stored theme id; an unknown id is the default. */',
    `    fun byId(id: String?): Palette = Themes.firstOrNull { it.id == id } ?: ${cap(base.id)}`,
    '',
    "    // The default theme's values, for code outside any theme (the mesh panel's defaults).",
    `    val raised = ${cap(base.id)}.raised`,
    `    val raisedFocus = ${cap(base.id)}.raisedFocus`,
    `    val Accents = ${cap(base.id)}.accents`,
    '    object SystemColors {',
  );
  for (const n of sys) k.push(`        const val ${n} = ${argb(base.system[n])}`);
  k.push('    }', '', `    // ${tokens['tv-focus'].$comment}`, '    object TvFocus {');
  for (const [n, v] of own(tokens['tv-focus'])) k.push(`        const val ${n} = ${argb(v)}`);
  k.push('    }', '}');

  return { [OUTPUTS.css]: css.join('\n') + '\n', [OUTPUTS.kotlin]: k.join('\n') + '\n' };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(render())) {
    fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, file), text);
    console.log('wrote', file);
  }
}
