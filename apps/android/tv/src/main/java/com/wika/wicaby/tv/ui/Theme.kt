@Composable
fun WicabyTheme(accent: Color, content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = darkColorScheme(
            primary = accent,
            onPrimary = onAccent(accent),
            background = C.bg,
            onBackground = C.label,
            surface = C.elevated,
            onSurface = C.label,
        ),
        typography = Typography(bodyLarge = Type.body, bodyMedium = Type.body, bodySmall = Type.footnote, titleLarge = Type.title2, labelLarge = Type.callout),
    ) {
        CompositionLocalProvider(LocalAccent provides accent, LocalContentColor provides C.label, content = content)
    }
}

